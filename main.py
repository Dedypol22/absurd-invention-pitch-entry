import os

LINE = "A self-drying umbrella that shakes itself like a wet dog the moment you step inside, then apologises to everyone it just sprayed."

def main():
    out = os.environ.get("MAKEFUN_OUTPUT_DIR", "/output")
    os.makedirs(out, exist_ok=True)
    with open(os.path.join(out, "entry.txt"), "w", encoding="utf-8") as f:
        f.write(LINE)

if __name__ == "__main__":
    main()
